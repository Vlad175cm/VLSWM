static const std::set<std::string> COLOR_KEYS = {
    "background", "foreground", "cursor-color", "cursor-text",
    "selection-background", "selection-foreground",
    "split-divider-color", "unfocused-split-fill",
};

static std::string trim(const std::string &s) {
    const char *ws = " \t\r\n\"'";
    size_t b = s.find_first_not_of(ws);
    if (b == std::string::npos) return "";
    size_t e = s.find_last_not_of(ws);
    return s.substr(b, e - b + 1);
}

static std::string config_file_path(const std::string &dir) {
    struct stat st;
    std::string modern = dir + "/config.ghostty";
    if (stat(modern.c_str(), &st) == 0) return modern;
    return dir + "/config";
}

static bool is_vlswm_file(const std::string &value) {
    size_t slash = value.find_last_of('/');
    std::string name = slash == std::string::npos ? value : value.substr(slash + 1);
    return name == VLSWM_THEME_FILE;
}

static void read_colors(const std::string &path, const std::string &dir, int depth,
                        std::map<std::string, std::string> &out) {
    if (depth > 3) return;
    std::ifstream in(path);
    if (!in) return;
    std::string line;
    while (std::getline(in, line)) {
        std::string s = trim(line);
        if (s.empty() || s[0] == '#') continue;
        size_t eq = s.find('=');
        if (eq == std::string::npos) continue;
        std::string key = trim(s.substr(0, eq));
        std::string value = trim(s.substr(eq + 1));

        if (key == "config-file") {
            if (is_vlswm_file(value)) continue;
            std::string inc = (!value.empty() && value[0] == '/') ? value : dir + "/" + value;
            read_colors(inc, dir, depth + 1, out);
        } else if (key == "palette") {
            size_t eq2 = value.find('=');
            if (eq2 == std::string::npos) continue;
            std::string index = trim(value.substr(0, eq2));
            std::string color = trim(value.substr(eq2 + 1));
            if (!color.empty() && color[0] == '#') out["palette:" + index] = color;
        } else if (COLOR_KEYS.count(key)) {
            if (!value.empty() && value[0] == '#') out[key] = value;
        }
    }
}

std::map<std::string, std::string> theme_read_base(const std::string &ghostty_dir) {
    std::map<std::string, std::string> out;
    read_colors(config_file_path(ghostty_dir), ghostty_dir, 0, out);
    return out;
}

std::string theme_invert(const std::string &hex) {
    if (hex.size() != 7 || hex[0] != '#') return hex;
    unsigned int rgb[3];
    for (int i = 0; i < 3; i++) {
        for (int j = 0; j < 2; j++) {
            if (!isxdigit((unsigned char)hex[1 + i * 2 + j])) return hex;
        }
        rgb[i] = (unsigned int)std::stoul(hex.substr(1 + i * 2, 2), nullptr, 16);
    }
    char out[8];
    std::snprintf(out, sizeof(out), "#%02x%02x%02x", 255 - rgb[0], 255 - rgb[1], 255 - rgb[2]);
    return out;
}

bool theme_write(const std::string &ghostty_dir,
                 const std::map<std::string, std::string> &base, bool white) {
    std::error_code ec;
    std::filesystem::create_directories(ghostty_dir, ec);
    std::string path = ghostty_dir + "/" + VLSWM_THEME_FILE;
    std::string tmp = path + ".tmp";

    std::ostringstream body;
    body << "# Generated by vlswm. Edit the theme with SUPER+T, not by hand.\n";
    body << "app-notifications = no-config-reload\n";
    for (const auto &kv : base) {
        std::string color = white ? theme_invert(kv.second) : kv.second;
        if (kv.first == "cursor-color") {
            color = white ? "#000000" : "#ffffff";
        } else if (kv.first == "cursor-text") {
            color = white ? "#ffffff" : "#000000";
        }
        if (kv.first.rfind("palette:", 0) == 0) {
            body << "palette = " << kv.first.substr(8) << "=" << color << "\n";
        } else {
            body << kv.first << " = " << color << "\n";
        }
    }

    std::ofstream out(tmp, std::ios::trunc);
    if (!out) {
        wlr_log(WLR_ERROR, "theme: cannot write '%s'", tmp.c_str());
        return false;
    }
    out << body.str();
    out.close();
    if (std::rename(tmp.c_str(), path.c_str()) != 0) {
        wlr_log(WLR_ERROR, "theme: cannot replace '%s'", path.c_str());
        return false;
    }
    return true;
}

bool theme_ensure_include(const std::string &ghostty_dir) {
    std::string config = config_file_path(ghostty_dir);
    const std::string line = std::string("config-file = ") + VLSWM_THEME_FILE;

    std::string content;
    {
        std::ifstream in(config);
        if (in) {
            std::stringstream ss;
            ss << in.rdbuf();
            content = ss.str();
        }
    }
    std::istringstream lines(content);
    std::string l;
    while (std::getline(lines, l)) {
        if (trim(l) == line) return true;
    }

    std::error_code ec;
    std::filesystem::create_directories(ghostty_dir, ec);
    std::ofstream out(config, std::ios::app);
    if (!out) {
        wlr_log(WLR_ERROR, "theme: cannot update '%s'", config.c_str());
        return false;
    }
    if (!content.empty() && content.back() != '\n') out << "\n";
    out << "\n# vlswm theme\n" << line << "\n";
    return true;
}

static const std::vector<std::string> FOOT_COLOR_KEYS = {
    "background", "foreground", "flash", "cursor",
    "selection-foreground", "selection-background",
    "regular0", "regular1", "regular2", "regular3",
    "regular4", "regular5", "regular6", "regular7",
    "bright0", "bright1", "bright2", "bright3",
    "bright4", "bright5", "bright6", "bright7",
};

static std::string foot_config_path(const std::string &dir) {
    return dir + "/foot.ini";
}

static std::string foot_default_color(const std::string &key) {
    if (key == "background") return "000000";
    if (key == "foreground") return "ffffff";
    if (key == "flash") return "ffffff";
    if (key == "cursor") return "ffffff 000000";
    if (key == "selection-foreground") return "000000";
    if (key == "selection-background") return "ffffff";
    if (key == "regular0") return "000000";
    if (key.rfind("regular", 0) == 0) return "ffffff";
    if (key == "bright0") return "666666";
    if (key.rfind("bright", 0) == 0) return "ffffff";
    return "ffffff";
}

static std::string strip_hash(const std::string &value) {
    std::string s = trim(value);
    if (!s.empty() && s[0] == '#') s.erase(0, 1);
    if (s.size() != 6) return "";
    for (char c : s) {
        if (!isxdigit((unsigned char)c)) return "";
    }
    return s;
}

static std::string invert_hex6(const std::string &value) {
    std::string s = strip_hash(value);
    if (s.empty()) return "";
    unsigned int channels[3];
    for (int i = 0; i < 3; i++) {
        channels[i] = (unsigned int)std::stoul(s.substr((size_t)i * 2, 2), nullptr, 16);
    }
    char out[7];
    std::snprintf(out, sizeof(out), "%02x%02x%02x",
                  255 - channels[0], 255 - channels[1], 255 - channels[2]);
    return out;
}

static std::string invert_value(const std::string &value) {
    std::istringstream ss(value);
    std::string token;
    std::string out;
    bool any = false;
    while (ss >> token) {
        std::string inverted = invert_hex6(token);
        if (inverted.empty()) return "";
        if (!out.empty()) out += " ";
        out += inverted;
        any = true;
    }
    return any ? out : "";
}

std::map<std::string, std::string> foot_theme_read_base(const std::string &foot_dir) {
    std::map<std::string, std::string> out;
    std::ifstream in(foot_config_path(foot_dir));
    if (!in) return out;

    std::string section;
    std::string line;
    while (std::getline(in, line)) {
        std::string s = trim(line);
        if (s.empty() || s[0] == '#') continue;
        if (s[0] == '[') {
            size_t end = s.find(']');
            section = end == std::string::npos ? "" : trim(s.substr(1, end - 1));
            continue;
        }
        if (section != "colors-dark" && section != "colors") continue;

        size_t eq = s.find('=');
        if (eq == std::string::npos) continue;
        std::string key = trim(s.substr(0, eq));
        std::string value = trim(s.substr(eq + 1));
        if (std::find(FOOT_COLOR_KEYS.begin(), FOOT_COLOR_KEYS.end(), key) !=
            FOOT_COLOR_KEYS.end()) {
            out[key] = value;
        }
    }
    return out;
}

bool foot_theme_write(const std::string &foot_dir,
                      const std::map<std::string, std::string> &base) {
    std::error_code ec;
    std::filesystem::create_directories(foot_dir, ec);
    std::string path = foot_dir + "/" + VLSWM_FOOT_THEME_FILE;
    std::string tmp = path + ".tmp";

    std::ostringstream body;
    body << "# Generated by vlswm. Edit colors in foot.ini, not here.\n";
    if (base.empty()) {
        body << "[colors-dark]\n";
        body << "alpha=1.0\n";
        for (const auto &key : FOOT_COLOR_KEYS) {
            body << key << "=" << foot_default_color(key) << "\n";
        }
    }
    body << "[colors-light]\n";
    body << "alpha=1.0\n";
    for (const auto &key : FOOT_COLOR_KEYS) {
        std::string value;
        auto it = base.find(key);
        if (it != base.end()) value = invert_value(it->second);
        if (value.empty()) value = invert_value(foot_default_color(key));
        body << key << "=" << value << "\n";
    }

    std::ofstream out(tmp, std::ios::trunc);
    if (!out) {
        wlr_log(WLR_ERROR, "foot theme: cannot write '%s'", tmp.c_str());
        return false;
    }
    out << body.str();
    out.close();
    if (std::rename(tmp.c_str(), path.c_str()) != 0) {
        wlr_log(WLR_ERROR, "foot theme: cannot replace '%s'", path.c_str());
        return false;
    }
    return true;
}

bool foot_theme_ensure_include(const std::string &foot_dir) {
    std::string config = foot_config_path(foot_dir);
    std::string content;
    {
        std::ifstream in(config);
        if (in) {
            std::stringstream ss;
            ss << in.rdbuf();
            content = ss.str();
        }
    }

    std::istringstream lines(content);
    std::string line;
    while (std::getline(lines, line)) {
        std::string s = trim(line);
        if (s.rfind("include=", 0) == 0 &&
            s.find(VLSWM_FOOT_THEME_FILE) != std::string::npos) {
            return true;
        }
    }

    std::error_code ec;
    std::filesystem::create_directories(foot_dir, ec);
    std::ofstream out(config, std::ios::trunc);
    if (!out) {
        wlr_log(WLR_ERROR, "foot theme: cannot update '%s'", config.c_str());
        return false;
    }
    out << "include=" << foot_dir << "/" << VLSWM_FOOT_THEME_FILE << "\n";
    if (!content.empty()) out << content;
    return true;
}
